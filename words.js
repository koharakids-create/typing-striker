const LEVELS = [
  { id: 0, name: 'ちょうしょしんしゃ', label: '超初心者', min: 1,  max: 3,  desc: '3もじまで' },
  { id: 1, name: 'しょしんしゃ',       label: '初心者',   min: 4,  max: 5,  desc: '4〜5もじ' },
  { id: 2, name: 'ちゅうきゅう',       label: '中級',     min: 6,  max: 7,  desc: '6〜7もじ' },
  { id: 3, name: 'じょうきゅう',       label: '上級',     min: 8,  max: 10, desc: '8〜10もじ' },
  { id: 4, name: 'プロきゅう',         label: 'プロ級',   min: 11, max: 99, desc: '11もじいじょう' },
];

const WORDS = (() => {
  const out = [];
  let cat = '用語';
  for (const raw of WORD_SOURCE.split('\n')) {
    const line = raw.trim();
    if (!line) continue;
    if (line.startsWith('#')) { cat = line.slice(1).trim(); continue; }
    const [text, yomi] = line.split('|');
    if (!text || !yomi) continue;
    const len = yomi.length;
    const lv = LEVELS.find(l => len >= l.min && len <= l.max);
    out.push({ text, yomi, cat, len, level: lv ? lv.id : 4 });
  }
  return out;
})();
